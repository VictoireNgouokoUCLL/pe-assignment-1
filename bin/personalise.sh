#!/usr/bin/env bash
#
# SASM Foundations - Assignment 1 - personalisation
#
# Derives your personal server specification from your GitHub username and
# writes two files:
#
#   spec.md   your assignment parameters, in readable form
#   .env      the same values, read automatically by docker compose
#
# Run it once, from the root of your repository:
#
#   ./bin/personalise.sh
#
# The values are derived deterministically: the same username always produces
# the same specification. Editing .env by hand does not give you an easier
# assignment - it only makes your submission fail the consistency check.
#
# Other modes (used by your lecturer, not by you):
#   ./bin/personalise.sh --csv <username>     one CSV row
#   ./bin/personalise.sh --env <username>     shell-style key=value
#   ./bin/personalise.sh --header             CSV header row

set -euo pipefail

# ---------------------------------------------------------------- value pools

WORDS=(atlas borea cedar delta ember flint grove harbor
       indigo juniper kestrel lumen mistral nimbus orion pallas)
NAMES=(anke bram cato dries elke fien gert hanne
       ilse joris karel lotte milan nora pieter ruben)
ZONES=(Europe/Brussels Europe/Lisbon Europe/Helsinki
       America/Toronto Asia/Tokyo Australia/Sydney)
LOCALES=(en_US.UTF-8 nl_BE.UTF-8 fr_BE.UTF-8 de_DE.UTF-8)
POOLS=(be.pool.ntp.org nl.pool.ntp.org europe.pool.ntp.org 0.debian.pool.ntp.org)
SOURCES=(/etc /srv/app /var/log)

# ------------------------------------------------------------------ seed maths

# byte N (0-255) of the sha256 of the username
_byte() { printf '%d' "0x${SEED_HEX:$(( $1 * 2 )):2}"; }

derive() {
  STUDENT="$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')"
  SEED_HEX="$(printf '%s' "$STUDENT" | sha256sum | cut -d' ' -f1)"

  HOSTNAME_="srv-${WORDS[$(( $(_byte 0) % 16 ))]}-$(( 10 + $(_byte 1) % 90 ))"
  GROUP_="${WORDS[$(( $(_byte 2) % 16 ))]}ops"

  ADMIN_USER="${NAMES[$(( $(_byte 3) % 16 ))]}"
  OPS_USER="${NAMES[$(( ( $(_byte 4) + 7 ) % 16 ))]}"
  SVC_USER="svc-${WORDS[$(( $(_byte 5) % 16 ))]}"

  # keep the two human accounts distinct
  if [ "$OPS_USER" = "$ADMIN_USER" ]; then
    OPS_USER="${NAMES[$(( ( $(_byte 4) + 11 ) % 16 ))]}"
  fi

  ADMIN_UID=$(( 1500 + $(_byte 6) % 80 ))
  OPS_UID=$((  1600 + $(_byte 7) % 80 ))
  SVC_UID=$((  1700 + $(_byte 8) % 80 ))

  SSH_PORT=$(( 2300 + $(_byte 9) % 60 ))

  TIMEZONE="${ZONES[$(( $(_byte 10) % 6 ))]}"
  LOCALE_="${LOCALES[$(( $(_byte 11) % 4 ))]}"
  NTP_POOL="${POOLS[$(( $(_byte 12) % 4 ))]}"

  BACKUP_SRC="${SOURCES[$(( $(_byte 13) % 3 ))]}"
  BACKUP_HOUR=$(( 1 + $(_byte 14) % 5 ))
  BACKUP_MIN=$((     ( $(_byte 15) % 12 ) * 5 ))
  RETENTION=$((  3 + $(_byte 16) % 12 ))
}

# -------------------------------------------------------------- detect student

detect_student() {
  local url repo
  url="$(git remote get-url origin 2>/dev/null || true)"
  if [ -z "$url" ]; then
    echo "ERROR: no git remote found. Run this from inside your cloned repository," >&2
    echo "       or pass your GitHub username: ./bin/personalise.sh <username>" >&2
    exit 1
  fi
  repo="$(basename "$url" .git)"
  case "$repo" in
    *pe-assignment-1-*) printf '%s' "${repo##*pe-assignment-1-}" ;;
    *)
      echo "ERROR: could not read your username from the repository name '$repo'." >&2
      echo "       Pass it explicitly: ./bin/personalise.sh <your-github-username>" >&2
      exit 1 ;;
  esac
}

# ------------------------------------------------------------------- rendering

write_env() {
  cat > .env <<EOF
# Generated by bin/personalise.sh - do not edit.
# This file is NOT a secrets file: commit it together with spec.md.
# docker compose reads it automatically for the values below.
SASM_STUDENT=$STUDENT
SASM_HOSTNAME=$HOSTNAME_
SASM_SSH_PORT=$SSH_PORT
EOF
}

write_spec() {
  cat > spec.md <<EOF
# Your server specification

Generated for GitHub user **$STUDENT**. These values are yours; your
neighbour's are different. Every requirement below is checked against exactly
these values, so copy them carefully.

| Setting | Your value |
|---|---|
| Server hostname | \`$HOSTNAME_\` |
| SSH port (on your host machine) | \`$SSH_PORT\` |
| Administrator account | \`$ADMIN_USER\`, UID \`$ADMIN_UID\` |
| Operator account | \`$OPS_USER\`, UID \`$OPS_UID\` |
| Service account | \`$SVC_USER\`, UID \`$SVC_UID\` |
| Shared group | \`$GROUP_\` |
| Timezone | \`$TIMEZONE\` |
| System locale | \`$LOCALE_\` |
| NTP pool | \`$NTP_POOL\` |
| Directory to back up | \`$BACKUP_SRC\` |
| Backup runs daily at | \`$(printf '%02d:%02d' "$BACKUP_HOUR" "$BACKUP_MIN")\` |
| Keep backups for | \`$RETENTION\` days |

Cron expression for that schedule, if you want to check your own: the minute
field is \`$BACKUP_MIN\` and the hour field is \`$BACKUP_HOUR\`.

> Re-running \`./bin/personalise.sh\` always produces this same table. If your
> values ever change, you ran it with a different username.
EOF
}

# ------------------------------------------------------------------------ main

case "${1:---write}" in
  --header)
    echo "student,hostname,ssh_port,admin_user,admin_uid,ops_user,ops_uid,svc_user,svc_uid,group,timezone,locale,ntp_pool,backup_src,backup_time,retention_days"
    ;;
  --csv)
    derive "${2:?usage: --csv <username>}"
    printf '%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%02d:%02d,%s\n' \
      "$STUDENT" "$HOSTNAME_" "$SSH_PORT" "$ADMIN_USER" "$ADMIN_UID" \
      "$OPS_USER" "$OPS_UID" "$SVC_USER" "$SVC_UID" "$GROUP_" \
      "$TIMEZONE" "$LOCALE_" "$NTP_POOL" "$BACKUP_SRC" \
      "$BACKUP_HOUR" "$BACKUP_MIN" "$RETENTION"
    ;;
  --env)
    derive "${2:?usage: --env <username>}"
    for v in STUDENT HOSTNAME_ SSH_PORT ADMIN_USER ADMIN_UID OPS_USER OPS_UID \
             SVC_USER SVC_UID GROUP_ TIMEZONE LOCALE_ NTP_POOL BACKUP_SRC \
             BACKUP_HOUR BACKUP_MIN RETENTION; do
      printf '%s=%s\n' "${v%_}" "${!v}"
    done
    ;;
  --write|"")
    derive "$(detect_student)"
    write_env
    write_spec
    echo "Wrote spec.md and .env for '$STUDENT'."
    echo "Read spec.md, then start the server with: docker compose up -d"
    ;;
  -h|--help)
    sed -n '2,25p' "$0" | sed 's/^# \{0,1\}//'
    ;;
  *)
    derive "$1"
    write_env
    write_spec
    echo "Wrote spec.md and .env for '$STUDENT'."
    ;;
esac
